#!/usr/bin/env python3
"""Convert the demo's kagent 1.x manifests (api.kagent.dev/v1alpha3) to kagent 0.x, including 0.9 (kagent.dev/v1alpha2).

The 1.x files stay the single source. The 0.9 copies in demo/lab/v1alpha2/ are generated from them, and
tests/test_demo_kagent09.py fails if a copy is stale or does not fit the 0.9.12 CRD shape.

  python3 demo/lab/to_v1alpha2.py demo/lab/demo-agents.yaml > demo/lab/v1alpha2/demo-agents.yaml
  python3 demo/lab/to_v1alpha2.py --write      # regenerate every copy

Agent: harnessRef is dropped (0.x has no Harness); template.inline becomes spec.declarative (systemPrompt -> systemMessage,
modelConfig {name} -> a plain name); an mcp tool becomes type McpServer with toolNames; a subAgent becomes type Agent naming
the evaluator Agent (0.x reaches it as a tool, and the worker can retry after a FAIL). ModelConfig: fields 0.9 does not have
(openAI.apiFormat, stream) are dropped. Every other object is copied unchanged.
"""
from __future__ import annotations

import argparse
import copy
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SOURCES = ["demo-agents.yaml", "broken-agent.yaml"]
OUT_DIR = HERE / "v1alpha2"
HEADER = "# GENERATED by demo/lab/to_v1alpha2.py from demo/lab/{src} for kagent 0.x, including 0.9 (kagent.dev/v1alpha2). Do not edit.\n"


def tool_v1alpha2(tool: dict, evaluator_agent: str | None) -> dict:
    if "mcp" in tool:
        srv = tool["mcp"]["server"]
        return {"type": "McpServer", "mcpServer": {"name": srv["name"], "kind": srv.get("kind", "RemoteMCPServer"),
                                                   "apiGroup": "kagent.dev", "toolNames": list(tool["mcp"].get("tools") or [])}}
    if "subAgent" in tool:
        if not evaluator_agent:
            raise ValueError(f"subAgent {tool['subAgent'].get('name')!r} needs an evaluator Agent name on 0.x")
        return {"type": "Agent", "agent": {"name": evaluator_agent}}
    raise ValueError(f"unknown tool shape: {sorted(tool)}")


def agent_v1alpha2(doc: dict, evaluator_agent: str | None = None) -> dict:
    inline = doc["spec"]["template"]["inline"]
    decl: dict = {"modelConfig": inline["modelConfig"]["name"], "systemMessage": inline["systemPrompt"]}
    if inline.get("tools"):
        decl["tools"] = [tool_v1alpha2(t, evaluator_agent) for t in inline["tools"]]
    spec = {"type": "Declarative", "description": inline.get("description", ""), "declarative": decl}
    return {"apiVersion": "kagent.dev/v1alpha2", "kind": "Agent", "metadata": copy.deepcopy(doc["metadata"]), "spec": spec}


def modelconfig_v1alpha2(doc: dict) -> dict:
    out = copy.deepcopy(doc)
    out["apiVersion"] = "kagent.dev/v1alpha2"
    out["spec"].pop("stream", None)
    (out["spec"].get("openAI") or {}).pop("apiFormat", None)
    return out


def convert(doc: dict, evaluator_agent: str | None = None) -> dict:
    if doc.get("apiVersion") == "api.kagent.dev/v1alpha3" and doc.get("kind") == "Agent":
        return agent_v1alpha2(doc, evaluator_agent)
    if doc.get("apiVersion") == "api.kagent.dev/v1alpha3" and doc.get("kind") == "ModelConfig":
        return modelconfig_v1alpha2(doc)
    if str(doc.get("apiVersion", "")).startswith("api.kagent.dev/"):
        raise ValueError(f"no 0.x form for {doc['apiVersion']} {doc.get('kind')}")
    return doc


def render(src: Path) -> str:
    docs = [convert(d) for d in yaml.safe_load_all(src.read_text()) if d]
    return HEADER.format(src=src.name) + yaml.safe_dump_all(docs, sort_keys=False, width=1000)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", nargs="?", type=Path)
    ap.add_argument("--write", action="store_true", help=f"regenerate demo/lab/v1alpha2/ from {', '.join(SOURCES)}")
    a = ap.parse_args()
    if a.write:
        OUT_DIR.mkdir(exist_ok=True)
        for name in SOURCES:
            (OUT_DIR / name).write_text(render(HERE / name))
        return 0
    if not a.source:
        ap.error("give a source file or --write")
    sys.stdout.write(render(a.source))
    return 0


if __name__ == "__main__":
    sys.exit(main())
