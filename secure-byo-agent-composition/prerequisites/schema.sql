CREATE SCHEMA secure_byo AUTHORIZATION kagent_owner;
GRANT USAGE ON SCHEMA secure_byo TO kagent_readwrite;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA secure_byo TO kagent_readwrite;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA secure_byo TO kagent_readwrite;
ALTER DEFAULT PRIVILEGES FOR ROLE kagent_owner IN SCHEMA secure_byo GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO kagent_readwrite;
ALTER DEFAULT PRIVILEGES FOR ROLE kagent_owner IN SCHEMA secure_byo GRANT USAGE, SELECT ON SEQUENCES TO kagent_readwrite;
